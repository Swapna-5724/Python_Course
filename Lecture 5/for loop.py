#  Loops are used for sequential traversal. For traversing list, string, tuples etc.

#  For loop

list = [1, 2, 3, 4, 5]

for num in list:
    print(num)


veggies = ["potato", "brinjal", "ladyfinger", "cucumber"]

for val in veggies:
    print(val)


#  for loop using Tuple

tup = (1, 2, 3, 4, 2, 8, 9)

for num in tup:
    print(num)


